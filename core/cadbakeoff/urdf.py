def urdf_joint_limits(spec_joint: dict[str, Any]) -> tuple[float, float]:
    """The joint's limits in the units a URDF file uses.

    URDF is metres, kilograms, radians. A revolute joint's limit is an angle,
    so it is radians in the spec and radians in the file. A prismatic joint's
    limit is a *distance*, and the spec carries distances in millimetres
    (the whole prop is designed in millimetres), while the file carries
    metres. So a prismatic limit is scaled by 1/1000 here, and the same
    conversion is used by the checker and by the action check, so the two
    arms of the bakeoff are measured on one scale.

    SolidCraft's own URDF export does the same thing: a slider joint whose
    limit is 300 mm is written as ``upper="0.3"``.
    """
    lo, hi = spec_joint["limits"]
    if spec_joint["type"] == "prismatic":
        return float(lo) / 1000.0, float(hi) / 1000.0
    return float(lo), float(hi)


def axis_rotation(axis: list[float]) -> tuple[float, float, float]:
    """The roll-pitch-yaw that turns local +Z into ``axis``.

    URDF's rpy is fixed-axis XYZ: R = Rz(yaw) Ry(pitch) Rx(roll).
    """
    x, y, z = axis
    norm = math.sqrt(x * x + y * y + z * z) or 1.0
    x, y, z = x / norm, y / norm, z / norm
    # The rotation about Z that takes +Z to the axis, with the smallest tilt.
    yaw = math.atan2(y, x)
    pitch = math.acos(max(-1.0, min(1.0, z)))
    # Rz(yaw) Ry(pitch) applied to (0,0,1) gives (sin(pitch)cos(yaw), sin(pitch)sin(yaw), cos(pitch)).
    if abs(x) + abs(y) < 1e-12:
        yaw = 0.0
    return (0.0, pitch, yaw)


def rpy_to_matrix(rpy: tuple[float, float, float]) -> list[list[float]]:
    r, p, y = rpy
    cr, sr = math.cos(r), math.sin(r)
    cp, sp = math.cos(p), math.sin(p)
    cy, sy = math.cos(y), math.sin(y)
    rx = [[1, 0, 0], [0, cr, -sr], [0, sr, cr]]
    ry = [[cp, 0, sp], [0, 1, 0], [-sp, 0, cp]]
    rz = [[cy, -sy, 0], [sy, cy, 0], [0, 0, 1]]
    return _matmul(_matmul(rz, ry), rx)


def _matmul(a: list[list[float]], b: list[list[float]]) -> list[list[float]]:
    return [[sum(a[i][k] * b[k][j] for k in range(3)) for j in range(3)] for i in range(3)]


def _matvec(m: list[list[float]], v: tuple[float, float, float]) -> tuple[float, float, float]:
    return tuple(sum(m[i][k] * v[k] for k in range(3)) for i in range(3))  # type: ignore[return-value]


