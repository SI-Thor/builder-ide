"""URDF: the build123d side is written here, and both sides are checked here.

Hy4 guard 4: SolidCraft exports URDF natively; build123d has no URDF export,
so one script writes it from the same frozen spec. The two URDFs are then
compared *in the world*, not by their text: each link's world placement and
each joint's world axis and limits are checked against the spec, so a
hand-written URDF that puts the hinge in the wrong place fails the check
instead of failing the physics.

The build123d URDF is generated by :func:`write_build123d_urdf`, which takes
the spec and the kernel's own mass properties and meshes. It is the same
function for every prop: nothing is written by hand.
"""

from __future__ import annotations

