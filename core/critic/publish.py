"""Publish the FP/FN table — the seat's deliverable, in Markdown.

The table is the artifact plan item 12 asks for: "the first
false-positive / false-negative table per defect class", published in
``core/critic/CALIBRATION.md``. Until a critic model is chosen and measured,
every row wears ``verdict@scripted`` on its face — the row is the baseline
that the model choice (week 3 item 18) has to beat.

The published file is **generated**, and it says so at the top. It carries:

* the table itself, one row per defect class, with the counts and the
  rates;
* the **band** verdict — whether the scripted checks catch the seeded
  defects without crying wolf on the clean frames — and, when they do not,
  which row failed and why;
* the **provenance** — where the renders came from, how many members there
  are, and the thresholds the checks used, each with the clean-control
  measurement it was set against.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Iterable, Sequence

from .checks import DEFAULT_THRESHOLDS, Thresholds
from .critic import CalibrationTable
from .models import DEFECT_TARGETS
from .set import MemberRecipe

__all__ = ["publish_table", "render_markdown"]

#: The header the published file carries. It says the file is generated, so
#: nobody hand-edits it and then loses their edit at the next growth.
_GENERATED_NOTE = (
    "<!-- Generated by core/critic/publish.py — do not edit by hand. -->\n"
    "<!-- Regenerate with: .venv/bin/python -m core.critic --grow --publish -->\n"
)


def render_markdown(
    table: CalibrationTable,
    *,
    members: Sequence[MemberRecipe] = (),
    thresholds: Thresholds | None = None,
    sources: Iterable[str] = (),
) -> str:
    """The published table, as Markdown."""
    t = thresholds or DEFAULT_THRESHOLDS
    lines: list[str] = []
    lines.append(_GENERATED_NOTE)
    lines.append("# The critic's calibration set — the first FP/FN table")
    lines.append("")
    lines.append(
        "Plan item 12 (week 2): *the critic's calibration set, first members* — "
        "a fixed reference set of ~30 **real renders** with seeded defects, run "
        "through the scripted checks, publishing false-positive and "
        "false-negative rates **per defect class**."
    )
    lines.append("")
    lines.append(
        "Every verdict in this table wears **`verdict@scripted`** on its face, "
        "because no critic *model* has been chosen and measured yet (X R4: the "
        "critic is \"the largest unchosen dependency in the whole stack\"). This "
        "row is the **baseline** that the model choice (week 3 item 18) has to "
        "beat."
    )
    lines.append("")

    # -- the set -------------------------------------------------------------
    lines.append("## The reference set")
    lines.append("")
    if members:
        by_defect: dict[str, int] = {}
        clean = 0
        for member in members:
            if member.defect is None:
                clean += 1
            else:
                by_defect[member.defect] = by_defect.get(member.defect, 0) + 1
        lines.append(
            f"**{len(members)} members** over real renders, "
            f"{clean} clean controls and {len(members) - clean} with a seeded "
            f"defect."
        )
        lines.append("")
        lines.append("| defect class | check | members |")
        lines.append("|---|---|---|")
        for defect in sorted(by_defect):
            lines.append(
                f"| `{defect}` | `{DEFECT_TARGETS[defect]}` | {by_defect[defect]} |"
            )
        lines.append(f"| *(clean controls)* | — | {clean} |")
        lines.append("")
    for source in sources:
        lines.append(f"- Renders: {source}")
    if sources:
        lines.append("")

    # -- the table -----------------------------------------------------------
    lines.append("## The table")
    lines.append("")
    lines.append(
        "| defect class | check | TP | FP | FN | TN | FP rate | FN rate | caught? |"
    )
    lines.append("|---|---|---|---|---|---|---|---|---|")
    for row in table.rows:
        fp_rate = "—" if row.counts.fp_rate is None else f"{row.counts.fp_rate:.1%}"
        fn_rate = "—" if row.counts.fn_rate is None else f"{row.counts.fn_rate:.1%}"
        caught = "yes" if row.counts.fn == 0 else "**no**"
        if row.members == 0:
            caught = "— (no members)"
        lines.append(
            f"| `{row.defect}` | `{row.check}` | {row.counts.tp} | {row.counts.fp} "
            f"| {row.counts.fn} | {row.counts.tn} | {fp_rate} | {fn_rate} | {caught} |"
        )
    lines.append("")
    lines.append(
        f"Totals: TP {table.totals.tp}, FP {table.totals.fp}, FN {table.totals.fn}, "
        f"TN {table.totals.tn}."
    )
    lines.append("")

    # -- the band ------------------------------------------------------------
    lines.append("## The band")
    lines.append("")
    lines.append(
        f"§1.9's band: **catch the seeded defects** (no false negatives) and "
        f"**reject no more than one in {1 / table.band.fp_bound:.0f} of the clean "
        f"ones**."
    )
    lines.append("")
    if table.in_band:
        lines.append(
            "**In band.** Every defect class's check catches its seeded defects, "
            "and no check fires on more than the band's fraction of the clean "
            "frames."
        )
    else:
        failing = [
            row
            for row in table.rows
            if row.members and not table.band.holds_for(row.counts)
        ]
        lines.append(
            "**Out of band.** The scripted checks do not yet hold the band, and "
            "the verdicts stay `verdict@scripted` — the plan's M2 named risk, as "
            "a measurement rather than a worry."
        )
        lines.append("")
        for row in failing:
            reason = []
            if row.counts.fn:
                reason.append(f"{row.counts.fn} missed")
            if row.counts.fp_rate is not None and row.counts.fp_rate > table.band.fp_bound:
                reason.append(
                    f"{row.counts.fp_rate:.1%} of the clean frames cried wolf"
                )
            lines.append(f"- `{row.defect}` (check `{row.check}`): {', '.join(reason)}.")
    lines.append("")

    # -- the thresholds ------------------------------------------------------
    lines.append("## The thresholds, and what they were measured on")
    lines.append("")
    lines.append(
        "Every threshold is set on a **measurement of the clean controls**, not "
        "a guess. The scripts that produce those numbers are "
        "`core/critic/measure_image.py` (the image checks) and "
        "`core/critic/measure_mesh.py` (the mesh checks), so the numbers can be "
        "re-derived from the same sweep."
    )
    lines.append("")
    lines.append("| threshold | value | what it was set against |")
    lines.append("|---|---|---|")
    for name, value, note in _threshold_notes(t):
        lines.append(f"| `{name}` | `{value}` | {note} |")
    lines.append("")

    # -- how to reproduce ----------------------------------------------------
    lines.append("## Reproducing this")
    lines.append("")
    lines.append("```bash")
    lines.append("# re-harvest the sweep, grow the set, re-score and publish")
    lines.append(".venv/bin/python -m core.critic --grow --publish")
    lines.append("")
    lines.append("# the clean frames' measurements (the thresholds' basis)")
    lines.append(".venv/bin/python core/critic/measure_image.py")
    lines.append("")
    lines.append("# the mesh half's measurements")
    lines.append(".venv/bin/python core/critic/measure_mesh.py <scene.blend>")
    lines.append("```")
    lines.append("")
    lines.append(
        "The set is a **recipe**, not a pile of pictures: every member records "
        "the base render's sha256 and the recipe of its seeded defect, so a "
        "member can be re-derived from the base render alone, and the table "
        "rebuilds from the members without the original images."
    )
    lines.append("")
    return "\n".join(lines)


def _threshold_notes(t: Thresholds) -> list[tuple[str, Any, str]]:
    """Each threshold, its value, and the measurement it was set against."""
    return [
        (
            "black_mean_luma",
            t.black_mean_luma,
            "the darkest clean frame's mean luminance was 0.103 (river-s5)",
        ),
        (
            "firefly_count",
            t.firefly_count,
            "the worst clean frame measured 154 isolated outliers (sun glitter on "
            "water, not a defect); the planted defects measure 307–472",
        ),
        (
            "flat_region_frac",
            t.flat_region_frac,
            "the largest exact-colour region in a clean frame was 30 px "
            "(0.006 % of the frame); the planted ones are 2.8 %–6.5 %",
        ),
        (
            "hole_min_contrast",
            t.hole_min_contrast,
            "the clean frames measured no uniform dark blob at all, so the "
            "threshold is the plant's own visibility margin",
        ),
        (
            "seam_min_strength",
            t.seam_min_strength,
            "the strongest four-sided rectangle in a clean frame steps by 0.286; "
            "the planted swaps step by 0.46 at their median",
        ),
        (
            "float_min_gap",
            t.float_min_gap,
            "the clean frames' candidate blobs reach 0.104 frame heights of open "
            "space under them at the ninth percentile",
        ),
        (
            "scale_max",
            t.scale_max,
            "the clean scenes' own prop families vary by up to 5.48× their "
            "family's median (a family of chopped trees holds stumps and whole "
            "trees), so the threshold sits above that natural spread",
        ),
        (
            "hollow_inward",
            t.hollow_inward,
            "the clean props' worst inward-facing fraction was 0.593 — vegetation "
            "is full of inward faces",
        ),
        (
            "edge_cut_margin",
            t.edge_cut_margin,
            "the closest a clean prop's middle comes to the picture's edge is "
            "0.0105 of its own half-width, and no clean scene has a prop that "
            "close",
        ),
    ]


def publish_table(
    table: CalibrationTable,
    path: str | Path,
    *,
    members: Sequence[MemberRecipe] = (),
    thresholds: Thresholds | None = None,
    sources: Iterable[str] = (),
) -> Path:
    """Write the table to ``core/critic/CALIBRATION.md``."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        render_markdown(table, members=members, thresholds=thresholds, sources=sources),
        encoding="utf-8",
    )
    return path
