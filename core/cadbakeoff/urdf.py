# checking a URDF against the spec
# ---------------------------------------------------------------------------


def _world_axis(joint: UrdfJoint) -> tuple[float, float, float]:
    rot = rpy_to_matrix(joint.rpy)
    return _matvec(rot, joint.axis)  # type: ignore[return-value]


def _world_joint_origin(model: UrdfModel, joint: UrdfJoint) -> tuple[float, float, float]:
    """Where the joint sits in the world, in metres.

    URDF's joint origin is the transform from the parent link's frame to the
    joint's frame; its translation is already in the parent's axes, so the
    rotation is not applied to it.
    """
    parent = model.world_transform(joint.parent)
    local = joint.origin
    return (
        parent[0][0] * local[0] + parent[0][1] * local[1] + parent[0][2] * local[2] + parent[0][3],
        parent[1][0] * local[0] + parent[1][1] * local[1] + parent[1][2] * local[2] + parent[1][3],
        parent[2][0] * local[0] + parent[2][1] * local[1] + parent[2][2] * local[2] + parent[2][3],
    )


def _world_axis(model: UrdfModel, joint: UrdfJoint) -> tuple[float, float, float]:
    """The joint's axis in the world."""
    parent = model.world_transform(joint.parent)
    rot = rpy_to_matrix(joint.rpy)
    local = _matvec(rot, joint.axis)
    return (
        parent[0][0] * local[0] + parent[0][1] * local[1] + parent[0][2] * local[2],
        parent[1][0] * local[0] + parent[1][1] * local[1] + parent[1][2] * local[2],
        parent[2][0] * local[0] + parent[2][1] * local[1] + parent[2][2] * local[2],
    )


def body_link_map(model: UrdfModel, spec: dict[str, Any]) -> dict[str, str]:
    """Which URDF link carries which body of the spec.

    The model is free to call its bodies what it likes — the prompt gives the
    names, but the design is the geometry, not the naming — so the bodies are
    matched through the joints, which the spec does name.
    """
    mapping: dict[str, str] = {}
    for spec_joint in spec["joints"]:
        joint = model.joints.get(spec_joint["name"])
        if joint is None:
            continue
        mapping.setdefault(spec_joint["parent"], joint.parent)
        mapping.setdefault(spec_joint["child"], joint.child)
    return mapping


def check_urdf_against_spec(model: UrdfModel, spec: dict[str, Any], *, tol_mm: float = 2.0) -> dict[str, Any]:
    """Check a URDF against the frozen spec: joints first, then the geometry."""
    problems: list[str] = []
    found: dict[str, Any] = {}
    params = dict(spec["parameters"])
    params["__density__"] = spec["density_kg_m3"]

    for spec_joint in spec["joints"]:
        joint = model.joints.get(spec_joint["name"])
        if joint is None:
            problems.append(f"joint {spec_joint['name']!r} is missing from the URDF")
            continue
        expected_type = "prismatic" if spec_joint["type"] == "prismatic" else "revolute"
        if joint.type != expected_type:
            problems.append(
                f"joint {spec_joint['name']!r} is {joint.type!r}, the spec says {expected_type!r}"
            )
        world_axis = _world_axis(model, joint)
        want_axis = [float(v) for v in spec_joint["axis"]]
        cos = sum(world_axis[i] * want_axis[i] for i in range(3))
        if abs(abs(cos) - 1.0) > 1e-3:
            problems.append(
                f"joint {spec_joint['name']!r} has the world axis {tuple(round(v, 4) for v in world_axis)}, "
                f"the spec says {tuple(want_axis)}"
            )
        world_origin = _world_joint_origin(model, joint)
        want_origin = [expr(v, params) for v in spec_joint["origin"]]
        offset = max(abs(world_origin[i] * 1000.0 - want_origin[i]) for i in range(3))
        if offset > tol_mm:
            problems.append(
                f"joint {spec_joint['name']!r} sits {offset:.2f} mm from where the spec puts it"
            )
        lo, hi = urdf_joint_limits(spec_joint)
        if joint.lower is None or joint.upper is None:
            problems.append(f"joint {spec_joint['name']!r} has no limits")
        else:
            if abs(joint.lower - lo) > 1e-3 or abs(joint.upper - hi) > 1e-3:
                problems.append(
                    f"joint {spec_joint['name']!r} has the limits [{joint.lower}, {joint.upper}], "
                    f"the spec says [{lo}, {hi}]"
                )
        found[spec_joint["name"]] = {
            "type": joint.type,
            "world_axis": list(world_axis),
            "world_origin_mm": [v * 1000.0 for v in world_origin],
            "limits": [joint.lower, joint.upper],
        }

    # The geometry: each body's world bounding box against the spec's cells.
    from core.cadbakeoff.analytic import build_cell

    links = body_link_map(model, spec)
    for body in spec["bodies"]:
        cells = [build_cell(c, params) for c in body["cells"]]
        lo = [min(c.aabb[i] for c in cells) for i in range(3)]
        hi = [max(c.aabb[i + 3] for c in cells) for i in range(3)]
        link_name = links.get(body["name"], body["name"])
        link = model.links.get(link_name)
        if link is None:
            problems.append(f"no URDF link carries the body {body['name']!r}")
            continue
        if not link.visual_mesh:
            problems.append(f"link {link_name!r} has no mesh")
            continue
        mesh_path = Path(model.source).parent / link.visual_mesh
        if not mesh_path.exists():
            problems.append(f"link {link_name!r} points at a mesh that is not there: {link.visual_mesh}")
            continue
        mesh = read_stl(mesh_path)
        transform = model.world_transform(link_name)
        rot = [
            [transform[i][j] for j in range(3)] for i in range(3)
        ]
        origin = (transform[0][3], transform[1][3], transform[2][3])
        vis_rot = rpy_to_matrix(link.visual_rpy)
        vis_origin = link.visual_origin
        world_points = []
        for v in mesh.vertices:
            # The visual's origin takes the mesh into the link's frame; the
            # link's frame then goes into the world.
            in_link = _matvec(vis_rot, v)
            in_link = (
                in_link[0] + vis_origin[0],
                in_link[1] + vis_origin[1],
                in_link[2] + vis_origin[2],
            )
            world = _matvec(rot, in_link)
            world_points.append(
                (world[0] + origin[0], world[1] + origin[1], world[2] + origin[2])
            )
        wlo = [min(p[i] for p in world_points) * 1000.0 for i in range(3)]
        whi = [max(p[i] for p in world_points) * 1000.0 for i in range(3)]
        want_lo = [lo[0], lo[1], lo[2]]
        want_hi = [hi[0], hi[1], hi[2]]
        delta = max(
            max(abs(wlo[i] - want_lo[i]), abs(whi[i] - want_hi[i])) for i in range(3)
        )
        if delta > tol_mm:
            problems.append(
                f"body {body['name']!r} sits {delta:.2f} mm from where the spec puts it "
                f"(urdf {tuple(round(v, 2) for v in wlo)}..{tuple(round(v, 2) for v in whi)}, "
                f"spec {tuple(round(v, 2) for v in want_lo)}..{tuple(round(v, 2) for v in want_hi)})"
            )
        found[body["name"]] = {
            "bbox_lo_mm": wlo,
            "bbox_hi_mm": whi,
            "bbox_delta_mm": delta,
        }

    return {"ok": not problems, "problems": problems, "found": found}


def compare_urdfs(a: UrdfModel, b: UrdfModel, spec: dict[str, Any]) -> dict[str, Any]:
    """Are the two URDFs the same robot? Compared in the world, not by text."""
    check_a = check_urdf_against_spec(a, spec)
    check_b = check_urdf_against_spec(b, spec)
    diffs: list[str] = []
    for joint in spec["joints"]:
        fa = check_a["found"].get(joint["name"])
        fb = check_b["found"].get(joint["name"])
        if not fa or not fb:
            diffs.append(f"joint {joint['name']!r} is missing from one of the URDFs")
            continue
        if fa["type"] != fb["type"]:
            diffs.append(f"joint {joint['name']!r} is {fa['type']} in one URDF and {fb['type']} in the other")
        axis_a, axis_b = fa["world_axis"], fb["world_axis"]
        cos = abs(sum(axis_a[i] * axis_b[i] for i in range(3)))
        if cos < 1.0 - 1e-3:
            diffs.append(f"joint {joint['name']!r} has a different world axis in the two URDFs")
        offset = max(abs(fa["world_origin_mm"][i] - fb["world_origin_mm"][i]) for i in range(3))
        if offset > 1.0:
            diffs.append(f"joint {joint['name']!r} is {offset:.2f} mm apart between the two URDFs")
        for side, key in (("lower", 0), ("upper", 1)):
            la = fa["limits"][key]
            lb = fb["limits"][key]
            if la is None or lb is None or abs(la - lb) > 1e-3:
                diffs.append(f"joint {joint['name']!r} has a different {side} limit")
    for body in spec["bodies"]:
        fa = check_a["found"].get(body["name"])
        fb = check_b["found"].get(body["name"])
        if not fa or not fb:
            diffs.append(f"body {body['name']!r} is missing from one of the URDFs")
            continue
        delta = max(
            abs(fa["bbox_lo_mm"][i] - fb["bbox_lo_mm"][i]) for i in range(3)
        ) + max(
            abs(fa["bbox_hi_mm"][i] - fb["bbox_hi_mm"][i]) for i in range(3)
        )
        if delta > 2.0:
            diffs.append(f"body {body['name']!r} is {delta:.2f} mm apart between the two URDFs")
    return {
        "equal": not diffs and check_a["ok"] and check_b["ok"],
        "diffs": diffs,
        "solidcraft": check_a,
        "build123d": check_b,
    }
